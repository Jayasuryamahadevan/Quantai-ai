import pandas as pd
from docx import Document
from docx.shared import Pt, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image as RLImage
from pathlib import Path
from datetime import datetime
import io
from html import escape

def generate_report(content: str, format_type: str, output_path: str) -> str:
    ext = format_type.lower()
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    
    date_str = datetime.now().strftime("%B %d, %Y")
    report_title = "QuantAI Automated Analysis Report"
    
    if ext == "csv":
        lines = [line.split(",") for line in content.split("\n") if line.strip()]
        if len(lines) > 1:
            df = pd.DataFrame(lines[1:])
            df.columns = [str(c).strip() for c in lines[0]]
            df.to_csv(output_path, index=False)
        else:
            df = pd.DataFrame([{"Analysis Content": content}])
            df.to_csv(output_path, index=False)
            
    elif ext == "docx":
        doc = Document()
        
        # Professional Title
        title = doc.add_heading(report_title, 0)
        title.alignment = WD_ALIGN_PARAGRAPH.CENTER
        
        # Date and Metadata
        meta = doc.add_paragraph(f"Generated on: {date_str}")
        meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
        meta.runs[0].font.size = Pt(10)
        meta.runs[0].font.italic = True
        
        doc.add_paragraph("_" * 60)
        
        # Split content into logical paragraphs and add them
        paragraphs = content.split('\n\n')
        for para in paragraphs:
            if para.strip():
                p = doc.add_paragraph(para.strip())
                p.style = 'Normal'
                p.paragraph_format.space_after = Pt(12)
                p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
                
        # Footer
        section = doc.sections[-1]
        footer = section.footer
        footer_para = footer.paragraphs[0]
        footer_para.text = "Generated by QuantAI AI Analyst - Confidential"
        footer_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        
        doc.save(output_path)
        
    elif ext == "pdf":
        doc = SimpleDocTemplate(
            output_path,
            pagesize=letter,
            rightMargin=72, leftMargin=72,
            topMargin=72, bottomMargin=18
        )
        
        styles = getSampleStyleSheet()
        styles.add(ParagraphStyle(
            name='QuantaiReportBody',
            parent=styles['Normal'],
            alignment=4,  # TA_JUSTIFY
            spaceAfter=12,
            fontSize=11,
            leading=16
        ))
        
        title_style = styles['Heading1']
        title_style.alignment = 1  # TA_CENTER
        
        meta_style = styles['Italic']
        meta_style.alignment = 1
        meta_style.textColor = "grey"
        
        story = []
        
        # Title & Meta
        story.append(Paragraph(report_title, title_style))
        story.append(Spacer(1, 0.2 * inch))
        story.append(Paragraph(f"Generated on: {date_str}", meta_style))
        story.append(Spacer(1, 0.5 * inch))
        
        # Content
        paragraphs = content.split('\n\n')
        for para in paragraphs:
            if para.strip():
                # ReportLab Paragraph treats input as markup. Escape document
                # text so symbols such as &, <, and > cannot break PDF output.
                clean_para = escape(para.strip().replace('\n', ' '))
                story.append(Paragraph(clean_para, styles['QuantaiReportBody']))
                
        doc.build(story)
        
    return output_path
